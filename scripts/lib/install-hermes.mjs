import { readFile, writeFile, mkdir, readdir, stat, cp } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, dirname } from "node:path";
const GENERATED_SKILL_HEADER = "<!-- generated by atomic install; edit skills/ instead -->\n";
async function listMarkdown(dir) {
  if (!existsSync(dir)) return [];
  return (await readdir(dir)).filter((f) => f.endsWith(".md")).sort();
}

export const HERMES_SKILLS_DIR = ".hermes/skills";
const HERMES_ONLY_SKILL = "atomic-hermes-delegate";

/** Printed after install; installer must not write ~/.hermes/config.yaml. */
export const HERMES_ORCHESTRATOR_CONFIG_HINT =
  "Hermes orchestrator: bridge via hermes-cursor-provider and set model.default: grok-4.7-medium in ~/.hermes/config.yaml (never *fast* models).";

/**
 * @param {string} skillMd
 * @returns {{ name: string | null, description: string | null }}
 */
function frontmatterFromSkillMd(skillMd) {
  const m = skillMd.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return { name: null, description: null };
  const block = m[1];
  const nameM = block.match(/^name:\s*(.+)$/m);
  const descM = block.match(/^description:\s*(.+)$/m);
  let description = descM ? descM[1].trim() : null;
  if (description?.startsWith('"') && description.endsWith('"')) {
    try {
      description = JSON.parse(description);
    } catch {
      description = description.slice(1, -1);
    }
  }
  return {
    name: nameM ? nameM[1].trim() : null,
    description,
  };
}

/**
 * @param {string} text
 */
function rewriteHermesSkillPaths(text) {
  return text
    .replace(/\.agents\/skills/g, ".hermes/skills")
    .replace(/`atomic-/g, "`atomic-");
}

/**
 * @param {string} root package root
 * @param {string} target
 * @param {boolean} force
 * @param {{ copied: string[], overwritten: string[], skipped: string[] }} record
 */
export async function installHermesSkills(root, target, force, record) {
  const srcSkills = join(root, "skills");
  const destRoot = join(target, HERMES_SKILLS_DIR);
  for (const entry of (await readdir(srcSkills)).sort()) {
    if (!entry.startsWith("atomic-")) continue;
    const src = join(srcSkills, entry);
    const st = await stat(src).catch(() => null);
    if (!st || !st.isDirectory()) continue;
    const dest = join(destRoot, entry);
    const skillMd = join(src, "SKILL.md");
    if (!existsSync(skillMd)) continue;
    let content = await readFile(skillMd, "utf8");
    content = rewriteHermesSkillPaths(content);
    const existed = existsSync(dest);
    if (existed && !force) {
      record.skipped.push(dest + "/");
      continue;
    }
    await mkdir(dest, { recursive: true });
    await cp(src, dest, { recursive: true, force: true });
    await writeFile(join(dest, "SKILL.md"), content, "utf8");
    record[existed ? "overwritten" : "copied"].push(dest + "/");
  }

  const commandsDir = join(root, "commands");
  if (existsSync(commandsDir)) {
    for (const file of await readdir(commandsDir)) {
      if (!file.endsWith(".md") || !file.startsWith("atomic-")) continue;
      const skillName = file.replace(/\.md$/, "");
      const skillPath = join(srcSkills, skillName, "SKILL.md");
      const commandBody = await readFile(join(commandsDir, file), "utf8");
      let description = `Atomic workflow /${skillName}`;
      let name = skillName;
      let body = commandBody.replace(/^<!--[^>]*-->\n?/, "").trim();
      body = body.replace(/\.agents\/skills/g, ".hermes/skills");
      if (existsSync(skillPath)) {
        const skillText = await readFile(skillPath, "utf8");
        const fm = frontmatterFromSkillMd(skillText);
        if (fm.name) name = fm.name;
        if (fm.description) description = fm.description;
        const skillBody = skillText.replace(/^---[\s\S]*?---\r?\n?/, "").trimStart();
        body = rewriteHermesSkillPaths(skillBody);
      }
      const skillMdOut = `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n${body}`;
      const dest = join(destRoot, skillName);
      const destFile = join(dest, "SKILL.md");
      const existed = existsSync(destFile);
      if (existed && !force) {
        record.skipped.push(destFile);
        continue;
      }
      await mkdir(dest, { recursive: true });
      await writeFile(destFile, GENERATED_SKILL_HEADER + skillMdOut, "utf8");
      record[existed ? "overwritten" : "copied"].push(destFile);
    }
  }
}

/**
 * @param {string} root
 * @param {string} target
 * @param {boolean} force
 * @param {{ copied: string[], overwritten: string[], skipped: string[] }} record
 */
export async function installHermesRoleSkills(root, target, force, record) {
  const agentsDir = join(root, "agents");
  const destRoot = join(target, HERMES_SKILLS_DIR);
  for (const file of await listMarkdown(agentsDir)) {
    const stem = file.replace(/\.md$/, "");
    const skillDir = `atomic-role-${stem}`;
    const dest = join(destRoot, skillDir);
    const destFile = join(dest, "SKILL.md");
    const raw = await readFile(join(agentsDir, file), "utf8");
    const fm = frontmatterFromSkillMd(raw);
    const body = raw.replace(/^---[\s\S]*?---\r?\n?/, "").trimStart();
    const name = fm.name ? `atomic-role-${fm.name}` : skillDir;
    const description = fm.description ?? `Atomic workflow role ${stem}`;
    const out = `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n${rewriteHermesSkillPaths(body)}`;
    const existed = existsSync(destFile);
    if (existed && !force) {
      record.skipped.push(destFile);
      continue;
    }
    await mkdir(dest, { recursive: true });
    await writeFile(destFile, out, "utf8");
    record[existed ? "overwritten" : "copied"].push(destFile);
  }
}

/**
 * Skills that must not land in .agents/skills (Hermes-only).
 * @param {string} entry skill dir name
 */
export function isHermesExclusiveSkill(entry) {
  return entry === HERMES_ONLY_SKILL;
}
