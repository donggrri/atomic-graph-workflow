/**
 * Public workflow names. New `atomic-*` names are canonical; old Cursor-prefixed names
 * remain install-time aliases so existing projects and habits keep working.
 */
export const LEGACY_NAME_MAP = Object.freeze({
  "cursor-atomic-workflow": "atomic-workflow",
  "cursor-atomic-lite": "atomic-lite",
  "cursor-atomic-explore": "atomic-explore",
  "cursor-atomic-plan": "atomic-plan",
  "cursor-atomic-task": "atomic-task",
  "cursor-atomic-execute": "atomic-execute",
  "cursor-atomic-review": "atomic-review",
  "cursor-atomic-wrapup": "atomic-wrapup",
  "cursor-atomic-run": "atomic-run",
  "cursor-atomic-delegate": "atomic-delegate",
  "cursor-atomic-agy": "atomic-agy",
  "cursor-atomic-status": "atomic-status",
  "cursor-atomic-doctor": "atomic-doctor",
  "cursor-atomic-config": "atomic-config",
  "cursor-atomic-settings": "atomic-settings",
  "cursor-atomic-models": "atomic-models",
  "cursor-atomic-setup": "atomic-setup",
  "cursor-atomic-reviewer": "atomic-reviewer",
});

export const CANONICAL_WORKFLOW_SKILL = LEGACY_NAME_MAP["cursor-atomic-workflow"];

const REVERSE_NAME_MAP = Object.freeze(
  Object.fromEntries(Object.entries(LEGACY_NAME_MAP).map(([legacy, canonical]) => [canonical, legacy])),
);

/** @param {string} name */
export function canonicalName(name) {
  return LEGACY_NAME_MAP[name] ?? name;
}

/** @param {string} name */
export function legacyName(name) {
  return REVERSE_NAME_MAP[name] ?? null;
}

/** @returns {Array<[string, string]>} */
export function legacySkillAliases() {
  return Object.entries(LEGACY_NAME_MAP).filter(([legacy]) => legacy !== "cursor-atomic-reviewer");
}

/**
 * Content for an installed legacy skill alias. The alias deliberately contains no workflow
 * instructions of its own, preventing the old and new names from drifting apart.
 * @param {string} legacy
 * @param {string} canonical
 */
export function legacySkillContent(legacy, canonical) {
  return `---\nname: ${legacy}\ndescription: "Deprecated alias for ${canonical}."\n---\n\n# /${legacy}\n\n이 이름은 이제 \`${canonical}\`로 변경되었습니다.\n\nRead and follow .agents/skills/${canonical}/SKILL.md exactly.\n`;
}

/** @param {string} legacy @param {string} canonical */
export function legacyCommandContent(legacy, canonical) {
  return `<!-- generated by atomic install; edit skills/ instead -->\nRead and follow the \`${canonical}\` skill from .agents/skills/${canonical}/SKILL.md.\n\nUser intent: $ARGUMENTS\n`;
}
