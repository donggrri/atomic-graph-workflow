async function listMarkdown(dir) {
  if (!existsSync(dir)) return [];
  return (await readdir(dir)).filter((f) => f.endsWith(".md")).sort();
}

export async function findLegacyCursorCommands(target) {
  return (await listMarkdown(join(target, LEGACY_CURSOR_COMMANDS_DIR)))
    .filter((f) => f.startsWith("cursor-atomic-"))
    .map((f) => join(target, LEGACY_CURSOR_COMMANDS_DIR, f));
}

async function removeLegacyCursorSkills(target) {
  const legacyRoot = join(target, LEGACY_CURSOR_SKILLS);
  if (!existsSync(legacyRoot)) return [];
  const removed = [];
  for (const entry of await readdir(legacyRoot)) {
    if (!entry.startsWith("cursor-atomic-")) continue;
    const path = join(legacyRoot, entry);
    await rm(path, { recursive: true, force: true });
    removed.push(path);
  }
  return removed;
}

async function installSkills(root, target, skillsDest, force, record) {
  const srcSkills = join(root, "skills");
  if (!existsSync(srcSkills)) {
    throw new Error(`skills/ 가 없습니다. 패키지 루트에서 실행하세요.`);
  }
  for (const entry of (await readdir(srcSkills)).sort()) {
    const src = join(srcSkills, entry);
    const st = await stat(src).catch(() => null);
    if (!st || !st.isDirectory()) continue;
    const dest = join(target, skillsDest, entry);
    const existed = existsSync(dest);
    if (existed && !force) {
      record.skipped.push(dest + "/");
      continue;
    }
    await mkdir(dirname(dest), { recursive: true });
    await cp(src, dest, { recursive: true, force });
    record[existed ? "overwritten" : "copied"].push(dest + "/");
  }
}

async function installCommandShims(root, target, relDir, force, record) {
  const srcDir = join(root, "commands");
  if (!existsSync(srcDir)) return;
  for (const file of await readdir(srcDir)) {
    if (!file.endsWith(".md")) continue;
    const dest = join(target, relDir, file);
    const existed = existsSync(dest);
    if (existed && !force) {
      record.skipped.push(dest);
      continue;
    }
    await mkdir(dirname(dest), { recursive: true });
    await cp(join(srcDir, file), dest, { force: true });
    record[existed ? "overwritten" : "copied"].push(dest);
  }
}

async function mergeAgentsMd(root, target, force, record) {
  const templatePath = join(root, "AGENTS.md");
  if (!existsSync(templatePath)) return;
  const template = await readFile(templatePath, "utf8");
  const inner = template.match(/<!-- atomic:begin[^>]*-->\r?\n([\s\S]*?)\r?\n<!-- atomic:end -->/);
  const body = inner ? inner[1] : template;
  const dest = join(target, "AGENTS.md");
  const prior = existsSync(dest) ? await readFile(dest, "utf8") : "";
  const merged = upsertBlock(prior, body);
  if (prior === merged && existsSync(dest) && !force) {
    record.skipped.push(dest);
    return;
  }
  await writeFile(dest, merged, "utf8");
  record[prior ? "overwritten" : "copied"].push(dest);
}

async function installClaudeMd(target, record) {
  const dest = join(target, "CLAUDE.md");
  const line = "@AGENTS.md\n";
  if (existsSync(dest)) {
    const text = await readFile(dest, "utf8");
    if (text.includes("@AGENTS.md")) {
      record.skipped.push(dest);
      return;
    }
    await writeFile(dest, `${text.trimEnd()}\n${line}`, "utf8");
    record.overwritten.push(dest);
  } else {
    await writeFile(dest, line, "utf8");
    record.copied.push(dest);
  }
}

async function installCursorRules(root, target, force, record) {
  const srcDir = join(root, RULES_SOURCE_DIR);
  if (!existsSync(srcDir)) return;
  for (const file of (await readdir(srcDir)).filter((f) => f.endsWith(".mdc")).sort()) {
    const dest = join(target, RULES_DIR, file);
    const existed = existsSync(dest);
    if (existed && !force) {
      record.skipped.push(dest);
      continue;
    }
    await mkdir(dirname(dest), { recursive: true });
    await cp(join(srcDir, file), dest, { force });
    record[existed ? "overwritten" : "copied"].push(dest);
  }
}

/**
 * @param {object} options
 */
export async function install(options = {}) {
  {
    const [maj, min] = process.version.slice(1).split(".").map(Number);
    if (maj < 22 || (maj === 22 && min < 13)) {
      console.warn(`warning: Node >=22.13 required (found ${process.version}); doctor.mjs will fail until Node is upgraded.`);
    }
  }
  const root = options.root || resolve(here, "..");
  const target = resolve(options.target || process.cwd());
  const force = !!options.force;
  const harnessParts = parseHarnessSpec(options.harness || "auto");
  const harnesses = resolveHarnesses(harnessParts, target, {
    withClaude: !!options.withClaude || harnessParts.includes("claude"),
  });
  const setModel = options.setModel || {};
  const record = { copied: [], overwritten: [], skipped: [], removed: [] };

  if (options.migrate) {
    record.removed.push(...(await removeLegacyCursorSkills(target)));
  }

  await installAtomicRuntime(root, target, { force });
  const neutralAgents = join(root, AGENTS_DIR);
  await copyAgentsToAtomic(neutralAgents, join(target, ".atomic", "agents"), force, record);
  await mergeAgentsMd(root, target, force, record);

  const skillsTargets = new Set([AGENTS_SKILLS_DIR]);
  if (harnesses.has("claude")) {
    skillsTargets.add(".claude/skills");
  }

  for (const skillsDir of skillsTargets) {
    await installSkills(root, target, skillsDir, force, record);
  }

  if (harnesses.has("cursor")) {
    await copyAgentsFlat(neutralAgents, join(target, ".cursor", "agents"), setModel, force, record);
    await installCursorRules(root, target, force, record);
  }

  if (harnesses.has("opencode")) {
    const srcAgents = neutralAgents;
    const destDir = join(target, ".opencode", "agents");
    for (const file of await listMarkdown(srcAgents)) {
      let content = await readFile(join(srcAgents, file), "utf8");
      content = opencodeAgentContent(content);
      const stem = file.replace(/\.md$/, "");
      const model = setModel[stem];
      if (model) content = applyModelOverride(content, model);
      const dest = join(destDir, file);
      const existed = existsSync(dest);
      if (existed && !force) {
        record.skipped.push(dest);
        continue;
      }
      await mkdir(destDir, { recursive: true });
      await writeFile(dest, content, "utf8");
      record[existed ? "overwritten" : "copied"].push(dest);
    }
    await installCommandShims(root, target, join(".opencode", "commands"), force, record);
  }

  if (harnesses.has("pi")) {
    await installCommandShims(root, target, join(".pi", "prompts"), force, record);
  }

  if (harnesses.has("claude")) {
    await copyAgentsFlat(neutralAgents, join(target, ".claude", "agents"), setModel, force, record);
    await installCommandShims(root, target, join(".claude", "commands"), force, record);
    await installClaudeMd(target, record);
  }

  const legacy = await findLegacyCursorCommands(target);
  return {
    target,
    harnesses: [...harnesses].sort(),
    skillsDir: AGENTS_SKILLS_DIR,
    legacy,
    ...record,
  };
}

if (process.argv[1] && process.argv[1].endsWith("install.mjs")) {
  let opts;
  try {
    opts = parseInstallArgs(process.argv.slice(2));
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
  if (opts.help) {
    printInstallHelp();
    process.exit(0);
  }
  install({ ...opts, root: resolve(here, "..") })
    .then((res) => {
      console.log(`설치 대상: ${res.target}`);
      console.log(`  하네스: ${res.harnesses.join(", ")}`);
      console.log(`  스킬: ${res.skillsDir}`);
      for (const f of res.copied) console.log(`  + ${f}`);
      for (const f of res.overwritten) console.log(`  ~ ${f}`);
      for (const f of res.skipped) console.log(`  = 유지: ${f}`);
      for (const f of res.removed) console.log(`  - 제거: ${f}`);
      if (res.legacy.length) {
        console.log("\n레거시 .cursor/commands/ 파일이 남아 있습니다:");
        for (const f of res.legacy) console.log(`  rm ${f}`);
      }
      console.log("\n검증: node .atomic/scripts/doctor.mjs --harness auto --target .");
    })
    .catch((err) => {
      console.error("설치 실패:", err.message);
      process.exit(1);
    });
}
